"use client";

import "@/features/platform-admin/components/blog/blog-content.css";

import Image from "@tiptap/extension-image";
import Link from "@tiptap/extension-link";
import Table from "@tiptap/extension-table";
import TableCell from "@tiptap/extension-table-cell";
import TableHeader from "@tiptap/extension-table-header";
import TableRow from "@tiptap/extension-table-row";
import Underline from "@tiptap/extension-underline";
import Youtube from "@tiptap/extension-youtube";
import { generateHTML } from "@tiptap/react";
import StarterKit from "@tiptap/starter-kit";
import { useMemo } from "react";

import type { TipTapDoc } from "@/features/platform-admin/types/blog.types";

/** Mirrors the public blog renderer so the preview matches what readers see. */
const PREVIEW_EXTENSIONS = [
  StarterKit.configure({ heading: { levels: [1, 2, 3, 4, 5, 6] } }),
  Underline,
  Link.configure({ openOnClick: false }),
  Image,
  Table,
  TableRow,
  TableHeader,
  TableCell,
  Youtube,
];

type RenderResult = { html: string } | { error: string };

function renderDoc(doc: TipTapDoc): RenderResult {
  try {
    return { html: generateHTML(doc, PREVIEW_EXTENSIONS) };
  } catch (error) {
    return { error: error instanceof Error ? error.message : "Unknown rendering error" };
  }
}

/** Client-only (loaded with ssr:false): TipTap's HTML generator needs the browser DOM. */
export default function BlogContentPreview({ doc }: { doc: TipTapDoc }) {
  const result = useMemo(() => renderDoc(doc), [doc]);
  if ("error" in result) {
    return (
      <p className="text-sm text-red-700" title={result.error}>
        This content could not be previewed. Open the editor to review it.
      </p>
    );
  }
  // Generated by TipTap from the stored document, which escapes text and drops unknown markup.
  return <div className="blog-prose" dangerouslySetInnerHTML={{ __html: result.html }} />;
}
